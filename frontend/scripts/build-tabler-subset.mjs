// Regenerate the bundled Tabler icon subset.
//
// The app ships only the glyphs it actually uses (~120), not the full
// 5,147-glyph webfont (447 KB). This script slices the upstream font down to
// the union of the writer-facing picker palette (`CURATED_ICONS`) and the
// app-chrome glyphs (`UI_GLYPHS`), and writes a self-contained stylesheet +
// woff2 into `src/lib/icons/generated/`, which `main.ts` imports.
//
// The full `@tabler/icons` / `@tabler/icons-webfont` packages stay installed
// but are consumed ONLY here — nothing in the app import graph references them,
// so Vite never bundles them. To promote a new glyph: add its name to the
// curated palette or `UI_GLYPHS`, then re-run `npm run icons:build` and commit
// the regenerated files.
//
// Usage: node scripts/build-tabler-subset.mjs   (or `npm run icons:build`)

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import subsetFont from "subset-font";
import { transformWithEsbuild } from "vite";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, ".."); // frontend/

// Load the plain string-array exports out of a TS source module without a
// build step: transpile to JS (type-only imports are erased) and import the
// result from a data: URL. Keeps a single source of truth — the glyph lists
// the app itself uses — rather than a hand-copied manifest.
async function loadTsExports(relPath) {
  const abs = resolve(root, relPath);
  const src = readFileSync(abs, "utf8");
  const { code } = await transformWithEsbuild(src, abs, { loader: "ts" });
  const url = `data:text/javascript;base64,${Buffer.from(code).toString("base64")}`;
  return import(url);
}

const { CURATED_ICONS } = await loadTsExports("src/lib/utils/fieldIcons.ts");
const { UI_GLYPHS } = await loadTsExports("src/lib/icons/uiGlyphs.ts");

// icons.json is the authoritative name -> codepoint map. Its package `exports`
// blocks the subpath, so read it by path.
const iconsMeta = JSON.parse(
  readFileSync(resolve(root, "node_modules/@tabler/icons/icons.json"), "utf8"),
);

const names = Array.from(new Set([...CURATED_ICONS, ...UI_GLYPHS])).sort();

// name -> codepoint (int). Fail loudly on any name the upstream set doesn't
// know — a typo must not silently ship as a blank glyph.
const missing = [];
const glyphs = [];
for (const name of names) {
  const hex = iconsMeta[name]?.styles?.outline?.unicode;
  if (!hex) {
    missing.push(name);
    continue;
  }
  glyphs.push({ name, codepoint: parseInt(hex, 16) });
}
if (missing.length > 0) {
  console.error(
    `Unknown Tabler glyph name(s) — not in @tabler/icons/icons.json:\n  ${missing.join("\n  ")}`,
  );
  process.exit(1);
}

// Subset the upstream TTF to just our codepoints (each icon is one PUA
// character) and emit woff2.
const ttf = readFileSync(
  resolve(root, "node_modules/@tabler/icons-webfont/dist/fonts/tabler-icons.ttf"),
);
const subsetText = glyphs.map((g) => String.fromCodePoint(g.codepoint)).join("");
const woff2 = await subsetFont(ttf, subsetText, { targetFormat: "woff2" });

// Base `.ti` rule copied verbatim from the upstream stylesheet so class
// behaviour is identical; then one `:before` rule per bundled glyph.
const version =
  JSON.parse(
    readFileSync(resolve(root, "node_modules/@tabler/icons-webfont/package.json"), "utf8"),
  ).version ?? "";

const glyphRules = glyphs
  .map((g) => `.ti-${g.name}:before{content:"\\${g.codepoint.toString(16)}"}`)
  .join("\n");

const css = `/* GENERATED by scripts/build-tabler-subset.mjs — do not edit by hand.
 * Curated Tabler ${version} subset: ${glyphs.length} of 5,147 glyphs (#315).
 * Regenerate with \`npm run icons:build\`. Glyph list = CURATED_ICONS (picker)
 * + UI_GLYPHS (app chrome). */
@font-face{font-family:"tabler-icons";font-style:normal;font-weight:400;src:url("./tabler-subset.woff2") format("woff2")}
.ti{font-family:"tabler-icons" !important;speak:none;font-style:normal;font-weight:normal;font-variant:normal;text-transform:none;line-height:1;-webkit-font-smoothing:antialiased;-moz-osx-font-smoothing:grayscale}
${glyphRules}
`;

const outDir = resolve(root, "src/lib/icons/generated");
mkdirSync(outDir, { recursive: true });
writeFileSync(resolve(outDir, "tabler-subset.woff2"), woff2);
writeFileSync(resolve(outDir, "tabler-subset.css"), css);

console.log(
  `Wrote ${glyphs.length} glyphs -> src/lib/icons/generated/ ` +
    `(woff2 ${(woff2.length / 1024).toFixed(1)} KB, was ~447 KB).`,
);
